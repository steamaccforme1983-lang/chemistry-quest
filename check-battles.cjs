const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {boot} = require('./check.cjs');
const app = boot();
const ui = app.elements;
const deck = JSON.parse(app.run('JSON.stringify(ALL_QUESTIONS.slice(0,5).map(q=>q.id))'));
const battle = {id:'demo', incoming:true, opponent:'Study friend', opponentIsOwner:true, status:'pending'};
const payloads = [];
app.context.battleRequest = async (action, body) => {
 assert.equal(action, 'progress');
 const command = body.progress._battle;
 payloads.push(command);
 if (command.action === 'accept') Object.assign(battle, {status:'accepted',deck});
 if (command.action === 'submit') Object.assign(battle, {status:'complete',submitted:true,yourScore:5,theirScore:3});
 return {playerCode:'CQ-123456ABCDEF',battles:[{...battle}]};
};
vm.runInContext(fs.readFileSync(__dirname+'/battles.js','utf8')+'\nsetupBattles(battleRequest);',app.context);
const settled = () => new Promise(resolve => setImmediate(resolve));
(async () => {
 ui['battles-open'].click();
 await settled();
 assert.equal(ui['battle-player-code'].textContent,'CQ-123456ABCDEF');
 assert.equal(ui['battle-list'].children[0].children[0].children[0].textContent,'Owner / Admin');
 const find = (parent, name) => parent.children.find(node => node.textContent === name);
 find(ui['battle-list'].children[0],'Accept').click();
 await settled();
 find(ui['battle-list'].children[0],'Play five questions').click();
 const play = ui['battle-play'];
 assert.equal(play.children[0].children[0].textContent,'Owner / Admin');
 const submit = find(play,'Submit answers');
 assert.equal(submit.disabled,true);
 const groups = play.children.filter(node => node.tagName === 'FIELDSET');
 assert.equal(groups.length,5);
 for (const group of groups) group.children[1].children[0].listeners.change[0]();
 assert.equal(submit.disabled,false);
 submit.click();
 await settled();
 assert.equal(payloads.at(-1).answers,'00000');
 assert.match(ui['battle-list'].children[0].children[1].textContent,/You won · You 5\/5 · Friend 3\/5/);
 console.log('PASS: friend battle list, acceptance, five required answers, submission payload and results.');
})().catch(error=>{console.error(error);process.exitCode=1;});
